// Turn the extracted v2 design pages into Next.js routes, byte-faithfully.
//
// The design's markup is emitted verbatim into each route via
// dangerouslySetInnerHTML. That is deliberate: the whole point of this move is
// that the approved design renders exactly as approved, so the markup must not be
// re-expressed as JSX where a formatter or a React normalisation could change it.
//
// What this preserves by NOT replacing the app:
//   - /papers/<slug>.md and /m/<slug>.html, cited in twelve deposited records
//   - scripts/check-site-rules.sh, which gates deploy.sh
//   - the worker, the build and the deploy pipeline
//
// Run: node scripts/emit-v2-pages.mjs <extracted-dir>

import { readFile, writeFile, mkdir } from "node:fs/promises";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const SRC = process.argv[2];
if (!SRC) {
  console.error("usage: emit-v2-pages.mjs <extracted-dir>");
  process.exit(1);
}

// file -> app route dir ("" means app/page.tsx, the index)
const PAGES = {
  "index.html": "",
  "new-here.html": "new-here",
  "for-carriers.html": "for-carriers",
  "science.html": "science",
  "routes.html": "routes",
  "open.html": "open",
  "experiments.html": "experiments",
  "papers.html": "papers",
  "census.html": "census",
  "data.html": "data",
  "history.html": "history",
  "limitations.html": "limitations",
};

function pick(html, re) {
  const m = re.exec(html);
  return m ? m[1] : "";
}

let hoverAll = new Set();
const emitted = [];

for (const [file, route] of Object.entries(PAGES)) {
  const html = await readFile(join(SRC, file), "utf8");
  const title = pick(html, /<title>([\s\S]*?)<\/title>/);
  const body = pick(html, /<body>([\s\S]*?)<\/body>/).trim();

  // Hover rules are identical across pages by construction; collect once.
  for (const s of html.matchAll(/<style>([\s\S]*?)<\/style>/g)) {
    for (const r of s[1].split("}")) {
      const t = r.trim();
      if (t.startsWith(".h")) hoverAll.add(t + "}");
    }
  }

  const dir = route ? join(root, "app", route) : join(root, "app");
  await mkdir(dir, { recursive: true });

  const tsx = `// GENERATED by scripts/emit-v2-pages.mjs from the approved Claude Design
// project "Brugada.net website redesign". Do not hand-edit: re-run the extractor.
//
// The markup is injected verbatim so the approved design renders exactly as
// approved. It is static, author-written HTML from our own design project -- no
// user input reaches it, so there is no injection surface here.

export const metadata = { title: ${JSON.stringify(title)} };

const HTML = ${JSON.stringify(body)};

export default function Page() {
  return <div dangerouslySetInnerHTML={{ __html: HTML }} />;
}
`;
  await writeFile(join(dir, "page.tsx"), tsx, "utf8");
  emitted.push(`app/${route ? route + "/" : ""}page.tsx  <- ${file}`);
}

// The design's own <head> styles, hoisted into one stylesheet the layout imports.
const css = `/* GENERATED by scripts/emit-v2-pages.mjs from the approved v2 design.
   These are the design's own head styles plus its style-hover rules, hoisted.
   Do not hand-edit: re-run the extractor. */
@import url("https://fonts.googleapis.com/css2?family=Source+Serif+4:ital,opsz,wght@0,8..60,400;0,8..60,600;1,8..60,400&display=swap");

body{margin:0;background:#161826;color:#e9e9ed;font-family:Inter,system-ui,sans-serif;font-size:15px}
a{color:#9184d9;text-underline-offset:3px}
a:hover{color:#b5abfc}

${[...hoverAll].sort((a, b) => (a.length - b.length) || a.localeCompare(b)).join("\n")}
`;
await writeFile(join(root, "app", "v2.css"), css, "utf8");

console.log(emitted.map((e) => "  " + e).join("\n"));
console.log(`\n  app/v2.css  (${hoverAll.size} hover rules)`);
console.log(`\n${emitted.length} routes emitted`);
